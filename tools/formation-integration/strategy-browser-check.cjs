async (page) => {
  const checks = [], errors = [], metrics = [];
  page.on('pageerror', e => errors.push(e.message));
  const assert = (value, message) => { if (!value) throw Error(message); checks.push(message); };
  const key = 'formation-integration';
  const endpoint = name => new URL('/api/' + name, page.url()).href;
  const status = async () => (await page.request.get(endpoint('status'), {headers: {'X-Frost-Key': key}})).json();
  const picker = () => page.getByRole('button', {name: '优先跳过的精英怪', exact: true});
  const search = () => page.getByRole('textbox', {name: '搜索精英', exact: true});
  const allNames = ['陪葬旗官','教团刽子手','大祭司','行走圣髑匣','锚持者','溺亡的宰相','堡垒甲虫','皇家收割者','石棺守卫','黑曜石刽子手','永冻守卫','霜之刽子手','嫁接师','砧木','首席屠夫','胆汁斟酒官','面孔缝纫师','模具搬运工','工头之屋','钟楼','葬礼潜行者','破冰兽'];
  const save = async () => {await page.locator('.autosave-status.saved').first().waitFor({timeout:15000});};
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button', {name:'策略参数', exact:true}).click();
  let s = await status();
  assert(s.config.avoidEliteIds.length === 0, '新配置默认空选，不默认避让陪葬旗官或其他精英');
  assert(JSON.stringify(s.config.formation) === JSON.stringify(['berserker','mago','arquera','paladin']), '截图指定的默认职业与站位保持不变');
  await picker().click();
  assert(await page.getByRole('checkbox').count() === 22, '多选包含资料站全部22种精英，含两个伏击精英');
  for (const name of allNames) assert(await page.getByRole('checkbox', {name, exact:true}).count() === 1, `列出精英：${name}`);
  await search().fill('冰川');
  assert(await page.getByRole('checkbox').count() === 2, '按大厅搜索精英');
  await search().fill('没有这样的精英');
  await page.getByText('没有匹配的精英，试试其他名称。', {exact:true}).waitFor();
  assert(await page.getByRole('checkbox').count() === 0, '搜索无结果有明确空态');
  await search().fill('');
  for (const name of allNames) await page.getByRole('checkbox', {name, exact:true}).check();
  assert(await page.getByRole('checkbox', {checked:true}).count() === 22, '全部22种可逐项多选，不只有单个精英可用');
  await page.keyboard.press('Escape');
  await save();
  s = await status();
  assert(s.config.avoidEliteIds.length === 22 && new Set(s.config.avoidEliteIds).size === 22, '全部22种选择经真实生产配置接口保存且无重复');
  await page.reload();
  await page.getByRole('button', {name:'策略参数',exact:true}).click();
  await picker().click();
  assert(await page.getByRole('checkbox', {checked:true}).count() === 22, '刷新页面完整恢复全部多选');
  const invalid = await page.request.post(endpoint('config'), {headers:{'X-Frost-Key':key},data:{...s.config,avoidEliteIds:['not-a-real-elite']}});
  assert(invalid.status() === 400 && (await status()).config.avoidEliteIds.length === 22, '后端拒绝非法精英ID，不覆盖合法名单');
  await page.getByRole('button', {name:'清空选择',exact:true}).click();
  assert(await page.getByRole('checkbox', {checked:true}).count() === 0, '一键清空恢复常规策略');
  await page.getByRole('checkbox', {name:'陪葬旗官',exact:true}).focus();
  await page.keyboard.press('Space');
  await page.waitForFunction(() => document.querySelector('[role="checkbox"][aria-label="陪葬旗官"]')?.getAttribute('aria-checked') === 'true');
  assert(await page.getByRole('checkbox', {name:'陪葬旗官',exact:true}).isChecked(), '键盘空格可切换精英选择');
  await page.getByRole('checkbox', {name:'破冰兽',exact:true}).check();
  await page.keyboard.press('Escape');
  await page.route('**/api/config', route => route.fulfill({status:400,contentType:'application/json',body:JSON.stringify({ok:false,error:'测试参数保存失败，请重试。'})}));
  await page.locator('.autosave-status.error').waitFor();
  assert(await page.locator('.elite-selected').innerText() === '陪葬旗官、破冰兽', '保存失败保留多选草稿并显示错误');
  await page.unroute('**/api/config');
  await save();
  assert((await status()).config.avoidEliteIds.length === 2, '保存失败后可重试成功');
  const closeError = page.getByRole('button', {name:'关闭错误',exact:true});
  if (await closeError.isVisible()) await closeError.click();
  for (const width of [1440,1024,768,390]) {
    await page.setViewportSize({width,height:1000});
    await picker().click();
    const metric = await page.locator('.elite-popover').evaluate((e,width) => {
      const r=e.getBoundingClientRect();return {width,left:r.left,right:r.right,documentWidth:document.documentElement.scrollWidth,viewport:innerWidth};
    }, width);
    metrics.push(metric);
    if (width === 1440 || width === 390) await page.screenshot({path:`output/playwright/strategy/elite-${width}-light.png`,animations:'disabled'});
    await page.keyboard.press('Escape');
  }
  assert(metrics.every(m => m.left>=0 && m.right<=m.viewport && m.documentWidth<=m.viewport), '1440/1024/768/390宽度的精英弹出层无横向溢出');
  await page.evaluate(() => localStorage.setItem('frost-theme','dark'));
  await page.reload();
  await page.getByRole('button', {name:'策略参数',exact:true}).click();
  await picker().click();
  await page.screenshot({path:'output/playwright/strategy/elite-390-dark.png',animations:'disabled'});
  await page.request.get(new URL('/test/state?active=1&run=1',page.url()).href);
  await page.waitForFunction(() => document.querySelector('[role="checkbox"][aria-label="陪葬旗官"]')?.disabled === true);
  assert(await page.getByRole('checkbox', {name:'陪葬旗官',exact:true}).isDisabled(), '运行状态变化时已打开的多选框也禁用');
  await page.keyboard.press('Escape');
  assert(await picker().isDisabled(), '运行中禁止修改精英名单');
  const during = await page.request.post(endpoint('config'), {headers:{'X-Frost-Key':key},data:s.config});
  assert(during.status() === 400, '生产接口也拒绝运行中改参数');
  await page.request.get(new URL('/test/state?active=0',page.url()).href);
  await page.waitForFunction(() => !document.querySelector('[aria-labelledby="elite-picker-label"]')?.disabled);
  await picker().click();
  await page.getByRole('button', {name:'清空选择',exact:true}).click();
  await page.keyboard.press('Escape');
  await save();
  assert((await status()).config.avoidEliteIds.length === 0, '清空名单可保存回默认普通策略');
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(() => window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/strategy/settings-desktop-dark.png',animations:'disabled'});
  assert(errors.length === 0,'浏览器无未处理异常');
  console.log('ELITE_CHECKS '+JSON.stringify({ok:true,checks,metrics,errors}));return {ok:true,checks,metrics,errors};
}
